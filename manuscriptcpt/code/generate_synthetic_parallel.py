def generate_synthetic_samples(num_samples: int = 3000):
    samples = []
    seen = set()
    
    attempts = 0
    max_attempts = num_samples * 20
    
    while len(samples) < num_samples and attempts < max_attempts:
        attempts += 1
        tpl = random.choice(TEMPLATES)
        
        # Pick slots
        subj_en, subj_am = random.choice(SLOTS["subj"])
        loc_en, loc_am = random.choice(SLOTS["loc"])
        obj_en, obj_am = random.choice(SLOTS["obj"])
        time_en, time_am = random.choice(SLOTS["time"])
        topic_en, topic_am = random.choice(SLOTS["topic"])
        adj_en, adj_am = random.choice(SLOTS["adj"])
        dis_en, dis_am = random.choice(SLOTS["disease"])
        act_en, act_am = random.choice(SLOTS["action"])
        num_en, num_am = random.choice(SLOTS["num"])
        item_en, item_am = random.choice(SLOTS["item"])
        
        slot_dict_en = {
            "subj_en": subj_en, "loc_en": loc_en, "obj_en": obj_en,
            "time_en": time_en, "topic_en": topic_en, "adj_en": adj_en,
            "disease_en": dis_en, "action_en": act_en, "num_en": num_en, "item_en": item_en
        }
        slot_dict_am = {
            "subj_am": subj_am, "loc_am": loc_am, "obj_am": obj_am,
            "time_am": time_am, "topic_am": topic_am, "adj_am": adj_am,
            "disease_am": dis_am, "action_am": act_am, "num_am": num_am, "item_am": item_am
        }
        
        en_text = tpl["en"].format(**slot_dict_en)
        am_text = tpl["am"].format(**slot_dict_am)
        
        pair_key = (en_text, am_text)
        if pair_key in seen:
            continue
        seen.add(pair_key)
        
        samples.append({
            "id": f"synth_{len(samples)+1:06d}",
            "english": en_text,
            "amharic": am_text,
            "domain": tpl["domain"],
            "source": "Synthetic-Generator-Template-v1",
            "is_synthetic": True,
            "limitations_note": "Rigid syntactic slot filling; lacks morpho-syntactic nuances of natural Amharic discourse."
        })
        
    return samples

def main():
    PROCESSED_DIR.mkdir(parents=True, exist_ok=True)
    print("Generating 3,000 synthetic English-Amharic parallel pairs...")
    synth_pairs = generate_synthetic_samples(3000)
    print(f"Generated {len(synth_pairs)} synthetic pairs.")
    
    out_file = PROCESSED_DIR / "synthetic_parallel_pairs.jsonl"
    with open(out_file, "w", encoding="utf-8") as f:
        for row in synth_pairs:
            f.write(json.dumps(row, ensure_ascii=False) + "\n")
    print(f"Saved synthetic dataset to {out_file}")

if __name__ == "__main__":
    main()

